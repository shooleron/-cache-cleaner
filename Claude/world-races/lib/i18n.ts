export function formatDate(iso: string, locale: Locale): string {
  const d = new Date(iso);
  return new Intl.DateTimeFormat(locale === "he" ? "he-IL" : "en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(d);
}

export function formatDuration(seconds: number | null | undefined): string {
  if (seconds == null || !Number.isFinite(seconds)) return "—";
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  if (h > 0) return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`;
  return `${m}:${String(s).padStart(2, "0")}`;
}

export function difficultyLabel(level: number | null, locale: Locale): string {
  if (!level) return "—";
  return t(locale, `race.difficulty.${level}`);
}

export function distanceCategory(km: number | null | undefined, locale: Locale): string {
  if (km == null) return "";
  if (km >= 220) return t(locale, "dist.ironman");        // Ironman 226
  if (km >= 110) return t(locale, "dist.half_ironman");   // 70.3 = 113
  if (km >= 160) return t(locale, "dist.ultra100m");      // 100 Mile = 160.9
  if (km >= 95) return t(locale, "dist.ultra100k");       // 100K and similar
  if (km >= 45) return t(locale, "dist.ultra50");         // 50K/56K ultra
  if (km >= 41 && km <= 43) return t(locale, "dist.marathon");  // 42.195
  if (km >= 20 && km <= 22) return t(locale, "dist.half");      // 21.0975
  if (km >= 9 && km <= 11) return t(locale, "dist.10k");
  if (km >= 4 && km <= 6) return t(locale, "dist.5k");
  if (km < 4) return t(locale, "dist.community");
  return `${km} ${t(locale, "race.km")}`;
}
